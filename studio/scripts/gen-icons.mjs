// Copies the Phosphor (light) icons the template uses into src/template/icons.js,
// so render.js can inline them without shipping the whole icon set.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = resolve(fileURLToPath(import.meta.url), '../..');
const NAMES = {
  scissors: 'scissors', palette: 'paint-brush', droplet: 'drop', sparkles: 'sparkle', razor: 'user', heart: 'heart',
  star: 'star', crown: 'crown-simple', leaf: 'leaf', sun: 'sun', gift: 'gift', calendar: 'calendar-blank',
  flower: 'flower-lotus', dryer: 'hair-dryer', clock: 'clock', pin: 'map-pin', phone: 'phone', mail: 'envelope-simple',
  arrow: 'arrow-up-right', next: 'arrow-right', prev: 'arrow-left',
  check: 'check', menu: 'list', close: 'x', desktop: 'desktop', mobile: 'device-mobile', magic: 'magic-wand',
  eye: 'eye', info: 'info', cart: 'shopping-cart-simple', rocket: 'rocket-launch', pen: 'pencil-simple-line', layout: 'layout',
  lock: 'lock-simple', globe: 'globe-simple', gauge: 'gauge', search: 'magnifying-glass', devices: 'devices',
  headset: 'headset', upload: 'upload-simple', plus: 'plus', minus: 'minus', drag: 'dots-six-vertical',
  arrowDown: 'arrow-down', copy: 'copy-simple', trash: 'trash-simple', arrowUp: 'arrow-up', reset: 'arrow-counter-clockwise', download: 'download-simple',
  instagram: 'instagram-logo', facebook: 'facebook-logo', tiktok: 'tiktok-logo', youtube: 'youtube-logo', linkedin: 'linkedin-logo', x: 'x-logo',
};
const out = {};
for (const [key, file] of Object.entries(NAMES)) {
  const svg = await readFile(resolve(root, `node_modules/@phosphor-icons/core/assets/light/${file}-light.svg`), 'utf8');
  out[key] = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
}
await writeFile(resolve(root, 'src/template/icons.js'), `// Generated by scripts/gen-icons.mjs from @phosphor-icons/core (MIT). Do not edit.\nexport const ICON_PATHS = ${JSON.stringify(out, null, 1)};\n`);
console.log(`✓ ${Object.keys(out).length} icons → src/template/icons.js`);

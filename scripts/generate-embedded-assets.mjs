import { readFileSync, writeFileSync } from 'node:fs'

const wasmJs = readFileSync('public/mediapipe/wasm/vision_wasm_internal.js').toString('base64')
const wasmBinary = readFileSync('public/mediapipe/wasm/vision_wasm_internal.wasm').toString('base64')
const model = readFileSync('public/models/face_landmarker.task').toString('base64')

const out = `// Auto-generated by scripts-generate-embedded-assets.mjs — do not edit by hand.
// Base64-embedded MediaPipe WASM runtime + face landmark model, used only by
// the standalone single-file build so it needs zero network/file fetches
// (see src/lib/faceShape.ts and vite.config.artifact.ts).
export const WASM_JS_B64 = ${JSON.stringify(wasmJs)};
export const WASM_BINARY_B64 = ${JSON.stringify(wasmBinary)};
export const MODEL_B64 = ${JSON.stringify(model)};
`

writeFileSync('src/generated/embeddedAssets.ts', out)
console.log('Wrote src/generated/embeddedAssets.ts:', (out.length / 1024 / 1024).toFixed(1), 'MB')

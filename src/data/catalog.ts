import type { Frame, FrameShape } from '../types'
import { FRAME_SHAPE_SUITABILITY } from './faceShapeFit'

let counter = 0
function frame(f: Omit<Frame, 'id' | 'suitedFor'> & { frameShape: FrameShape }): Frame {
  counter += 1
  return {
    ...f,
    id: `${f.brand}-${counter}`,
    suitedFor: FRAME_SHAPE_SUITABILITY[f.frameShape],
  }
}

